const hexA = [0x46, 0x76, 0x6f];
const hexB = [0xe6, 0xec, 0xec];
const mix = (t) => {
  const c = hexA.map((a, i) => Math.round(a + (hexB[i] - a) * t));
  return `rgb(${c[0]}, ${c[1]}, ${c[2]})`;
};

export default function WorldDots({ className = '' }) {
  const dots = useMemo(() => {
    const arr = [];
    for (const [r, segs] of Object.entries(ROWS)) {
      for (const [a, b] of segs) {
        for (let c = a; c <= b; c++) arr.push([c, Number(r)]);
      }
    }
    return arr;
  }, []);

  return (
    <svg
      className={className}
      viewBox={`0 0 ${WORLD_COLS * PITCH} ${WORLD_ROWS * PITCH}`}
      preserveAspectRatio="xMidYMid slice"
      aria-hidden="true"
      focusable="false"
    >
      {dots.map(([c, r], i) => {
        const t = c / (WORLD_COLS - 1);
        return (
          <circle
            key={i}
            cx={c * PITCH + PITCH / 2}
            cy={r * PITCH + PITCH / 2}
            r={1.7}
            fill={mix(t)}
            fillOpacity={0.5 + 0.4 * t}
          />
        );
      })}
    </svg>
  );
}
